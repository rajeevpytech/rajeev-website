// Real React/DOM interactions with no backend, storage or network dependencies.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import { JSDOM } from 'jsdom';
import React, { act } from 'react';
import { renderToString } from 'react-dom/server';

const require = createRequire(import.meta.url);
const { HelmetProvider } = require('react-helmet-async');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const temporary = path.join(root, 'node_modules/.cache/project-brief-tests');
fs.mkdirSync(temporary, { recursive: true });
const common = { bundle: true, platform: 'node', format: 'cjs', target: 'node18', packages: 'external', jsx: 'automatic', alias: { '@': path.join(root, 'src') }, loader: { '.js': 'jsx', '.jsx': 'jsx' }, logLevel: 'warning' };
await build({ ...common, entryPoints: [path.join(root, 'src/lib/projectBrief.js')], outfile: path.join(temporary, 'helpers.cjs') });
await build({ ...common, entryPoints: [path.join(root, 'src/pages/ProjectBriefBuilder.jsx')], outfile: path.join(temporary, 'component.cjs') });
const helpers = require(path.join(temporary, 'helpers.cjs'));
const Component = require(path.join(temporary, 'component.cjs')).default;
let checks = 0;
const verify = (condition, message) => { assert.ok(condition, message); checks += 1; };

verify(Object.keys(helpers.validateBrief(helpers.emptyBrief())).sort().join(',') === 'goal,services', 'Empty form requires project type and goal');
const full = { ...helpers.emptyBrief(), projectName: 'ACME / Pilot', services: ['web', 'ai'], goal: 'Reduce enquiry handling time', audience: 'Customers and staff', countries: 'India', languages: 'English and Hindi', pages: 'Home, booking', features: ['accounts', 'payments'], roles: 'Customer, administrator', integrationPlan: 'none', contentOwner: 'shared', timeline: 'First review next month', reviewChecks: ['privacy'] };
verify(Object.keys(helpers.validateBrief(full)).length === 0, 'A budget is not required');
verify(helpers.completionSections(full).filter(section => section.complete).length === 6, 'Six completion rules are transparent and budget stays optional');
verify(helpers.validateBrief({ ...full, currentUrl: 'javascript:alert(1)' }).currentUrl, 'Unsafe current URLs are rejected');
verify(helpers.validateBrief({ ...full, currentUrl: 'https://user:password@example.com' }).currentUrl, 'Credentials do not belong in the brief URL');
verify(helpers.validateBrief({ ...full, roles: '' }).roles, 'Account features need roles or an explicit open question');
verify(helpers.validateBrief({ ...full, integrationPlan: 'list', integrations: '' }).integrations, 'Named integrations cannot be empty');
verify(helpers.acceptanceChecklist(full).some(item => item.includes('sandbox')), 'Payment acceptance checks are generated from the selection');
verify(helpers.acceptanceChecklist(full).some(item => item.includes('human escalation')), 'AI acceptance checks include escalation');
verify(helpers.briefDocument(full) === helpers.briefDocument(full), 'Brief generation is deterministic');
const attack = helpers.briefDocument({ ...full, goal: 'A safe goal\n# INJECTED\n<script>alert(1)</script> [click](javascript:bad)' });
verify(!attack.includes('\n# INJECTED') && !attack.includes('<script>') && attack.includes('&lt;script&gt;'), 'Markdown escapes user headings, HTML and links');
verify(helpers.briefFilename({ projectName: '../../ACME / Pilot' }) === 'acme-pilot.md', 'Download names cannot contain path traversal');

const network = [];
const originalFetch = globalThis.fetch;
globalThis.fetch = (...args) => { network.push(args); throw new Error('Unexpected network request'); };
HelmetProvider.canUseDOM = false;
const helmetContext = {};
const serverHtml = renderToString(React.createElement(HelmetProvider, { context: helmetContext }, React.createElement(Component)));
verify((serverHtml.match(/<h1\b/g) || []).length === 1 && serverHtml.includes('A clearer brief.'), 'SSR has a useful, single H1');
verify(serverHtml.includes('Main business goal') && serverHtml.includes('Suggested acceptance checks'), 'SSR renders useful planning content before JavaScript');
verify(serverHtml.includes('ph-no-capture') && serverHtml.includes('data-ph-no-autocapture="true"'), 'The complete tool is excluded from existing automatic capture');
const serverDocument = new JSDOM(serverHtml);
verify(serverDocument.window.document.querySelector('title')?.textContent === 'Project Brief Builder — Plan Your Website, App or Automation | Rajeev Freelancer', 'Only the new tool gets its exact new metadata');
serverDocument.window.close();

const dom = new JSDOM('<!doctype html><html><head></head><body><div id="mount"></div></body></html>', { url: 'https://rajeevfreelancer.com/project-brief' });
for (const key of ['window', 'document', 'HTMLElement', 'HTMLInputElement', 'HTMLTextAreaElement', 'HTMLSelectElement', 'Event', 'MouseEvent', 'Node']) globalThis[key] = dom.window[key];
Object.defineProperty(globalThis, 'navigator', { configurable: true, value: dom.window.navigator });
globalThis.IS_REACT_ACT_ENVIRONMENT = true;
HelmetProvider.canUseDOM = true;
const storageCalls = [];
const setItem = dom.window.Storage.prototype.setItem;
dom.window.Storage.prototype.setItem = function (...args) { storageCalls.push(args); return setItem.apply(this, args); };
dom.window.XMLHttpRequest.prototype.open = (...args) => { network.push(args); throw new Error('Unexpected XMLHttpRequest'); };
const copies = [];
Object.defineProperty(navigator, 'clipboard', { configurable: true, value: { writeText: async text => { copies.push(text); } } });
const blobs = [], downloads = [];
const originalCreate = URL.createObjectURL, originalRevoke = URL.revokeObjectURL;
URL.createObjectURL = blob => { blobs.push(blob); return `blob:project-brief-${blobs.length}`; };
URL.revokeObjectURL = () => {};
const originalClick = dom.window.HTMLAnchorElement.prototype.click;
dom.window.HTMLAnchorElement.prototype.click = function () { downloads.push({ href: this.getAttribute('href'), filename: this.download }); };
const { createRoot } = await import('react-dom/client');
const client = createRoot(document.getElementById('mount'));
await act(async () => { client.render(React.createElement(HelmetProvider, null, React.createElement(Component))); });
const input = async (id, value) => {
  const el = document.getElementById(id);
  verify(!!el, `Input exists: ${id}`);
  const prototype = el.tagName === 'TEXTAREA' ? dom.window.HTMLTextAreaElement.prototype : el.tagName === 'SELECT' ? dom.window.HTMLSelectElement.prototype : dom.window.HTMLInputElement.prototype;
  await act(async () => {
    Object.getOwnPropertyDescriptor(prototype, 'value').set.call(el, value);
    el.dispatchEvent(new dom.window.Event(el.tagName === 'SELECT' ? 'change' : 'input', { bubbles: true }));
  });
};
const click = async element => { verify(!!element, 'Clickable control exists'); await act(async () => { element.click(); }); };
const button = label => [...document.querySelectorAll('button')].find(element => element.textContent.trim() === label);
const submit = async () => { await act(async () => { document.querySelector('form').dispatchEvent(new dom.window.Event('submit', { bubbles: true, cancelable: true })); }); };
verify(network.length === 0 && storageCalls.length === 0 && copies.length === 0 && downloads.length === 0, 'Loading does not submit, save, copy or download');
const ids = [...document.querySelectorAll('[id]')].map(element => element.id);
verify(new Set(ids).size === ids.length, 'All field, section and preview IDs are unique');
verify([...document.querySelectorAll('[aria-describedby]')].every(element => element.getAttribute('aria-describedby').split(' ').every(id => !id || document.getElementById(id))), 'Helper descriptions point to real elements');
await submit();
verify(document.querySelector('[role="alert"]')?.textContent.includes('Choose at least one'), 'Actual empty form shows validation errors');
verify(!document.getElementById('brief-output'), 'Invalid form has no export preview');
await click(document.getElementById('brief-service-web'));
await click(document.getElementById('brief-service-ai'));
await input('brief-projectName', '../../ACME / Pilot');
const privateGoal = 'PRIVATE DRAFT: reduce customer enquiry handling time';
await input('brief-goal', privateGoal);
await input('brief-currentUrl', 'javascript:alert(1)');
await submit();
verify(document.getElementById('brief-currentUrl-error')?.textContent.includes('http://'), 'Actual current-URL validation rejects an unsafe scheme');
await input('brief-currentUrl', 'https://example.com');
await input('brief-audience', 'Customers and staff');
await input('brief-countries', 'India and UK');
await input('brief-languages', 'English and Hindi');
await input('brief-pages', 'Home, services and booking');
await click(document.getElementById('brief-feature-accounts'));
await click(document.getElementById('brief-feature-payments'));
await input('brief-roles', 'Customer and administrator');
await input('brief-integrationPlan', 'list');
await input('brief-integrations', 'Existing CRM');
await input('brief-contentOwner', 'shared');
await input('brief-timeline', 'First design review next month');
await click(document.getElementById('brief-review-privacy'));
verify(document.querySelector('progress').value === 6, 'Actual form reaches six completed sections without a budget');
verify([...new dom.window.FormData(document.querySelector('form')).entries()].length === 0, 'No named draft fields can serialize into a native form URL');
await submit();
const preview = document.getElementById('brief-output');
verify(preview?.value.includes(privateGoal) && preview.value.includes('sandbox'), 'Generated preview contains the supplied goal and selection-based acceptance checks');
verify(document.querySelector('[data-testid="project-brief-builder"]').classList.contains('ph-no-capture'), 'User-generated preview remains inside capture-excluded root');
await click(button('Copy brief'));
verify(copies.length === 1 && copies[0] === preview.value, 'Copy occurs only after an explicit click and contains the visible preview');
await click(button('Download .md'));
verify(downloads.length === 1 && downloads[0].href.startsWith('blob:') && downloads[0].filename === 'acme-pilot.md', 'Markdown download uses a local Blob and safe filename');
verify(blobs[0].type === 'text/markdown;charset=utf-8' && await blobs[0].text() === preview.value, 'Downloaded Markdown matches the user-reviewed preview');
await click(button('Text'));
await click(button('Download .txt'));
verify(downloads[1].filename === 'acme-pilot.txt' && blobs[1].type === 'text/plain;charset=utf-8', 'Plain-text export has the correct filename and MIME type');
verify(await blobs[1].text() === document.getElementById('brief-output').value, 'Plain-text export matches its preview');
await input('brief-goal', privateGoal + ' with a second phase');
verify(button('Copy brief').disabled && button('Download .txt').disabled, 'Changed drafts cannot accidentally export an older generated snapshot');
await submit();
verify(!button('Copy brief').disabled && document.getElementById('brief-output').value.includes('second phase'), 'Regenerating refreshes the export');
const contact = document.querySelector('a[aria-label="Open contact page in a new tab"]');
verify(contact.getAttribute('href') === '/contact' && !contact.getAttribute('href').includes('?'), 'Contact CTA never contains private brief data');
verify(network.length === 0 && storageCalls.length === 0, 'Editing, generating and exporting never call the network or browser storage');
await click(button('Clear brief'));
verify(document.getElementById('brief-goal').value === '' && !document.getElementById('brief-output') && document.querySelector('progress').value === 0, 'Explicit clear resets the entire draft and generated output');
verify([...document.querySelectorAll('input[type="checkbox"]')].every(element => !element.checked), 'Clear resets all selected options');
verify(button('Copy brief').disabled && button('Download .md').disabled, 'No cleared data can be exported');
await act(async () => { client.unmount(); });
URL.createObjectURL = originalCreate; URL.revokeObjectURL = originalRevoke;
dom.window.HTMLAnchorElement.prototype.click = originalClick;
globalThis.fetch = originalFetch;
dom.window.close();
console.log(`PASS: ${checks} project brief helper, SSR, actual form, privacy and export assertions; 0 network calls and 0 storage writes.`);
